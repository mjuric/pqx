"""Generate a synthetic LSST-DiaSource-like Parquet file for demos and tests.

    python -m pqx.demo demo.parquet --rows 1000000
"""
from __future__ import annotations

import argparse
import datetime as dt

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq

BANDS = np.array(list("ugrizy"))


def make_table(n: int, seed: int = 42) -> pa.Table:
    rng = np.random.default_rng(seed)
    # A footprint like LSST's: southern sky plus an ecliptic band.
    ra = rng.uniform(0, 360, n)
    dec = np.degrees(np.arcsin(rng.uniform(-1.0, 0.25, n)))
    ecl = rng.random(n) < 0.3
    lam = np.radians(rng.uniform(0, 360, ecl.sum()))
    beta = np.radians(rng.normal(0, 5, ecl.sum()))
    eps = np.radians(23.439)
    sd = np.sin(beta) * np.cos(eps) + np.cos(beta) * np.sin(eps) * np.sin(lam)
    dec[ecl] = np.degrees(np.arcsin(sd))
    ra[ecl] = np.degrees(np.arctan2(np.sin(lam) * np.cos(eps) - np.tan(beta) * np.sin(eps), np.cos(lam))) % 360

    mag = rng.normal(22.0, 1.2, n).clip(16, 26)
    flux = (10 ** (-0.4 * (mag - 31.4))).astype(np.float32)  # nJy
    flux_err = (flux * rng.uniform(0.01, 0.2, n)).astype(np.float32)
    snr = flux / flux_err
    ss = rng.integers(0, max(n // 20, 1), n)
    ss_obj = np.where(ecl, ss + 1_000_000, 0).astype(np.int64)
    ss_mask = ss_obj == 0
    mjd = np.sort(rng.uniform(60800.0, 61200.0, n))
    ts = [dt.datetime(2025, 1, 1) + dt.timedelta(seconds=int(s)) for s in rng.integers(0, 3.15e7, min(n, 1))]
    ingest = pa.array(
        (np.datetime64("2025-06-01") + (mjd - 60800.0) * np.timedelta64(86400, "s").astype("timedelta64[ms]"))
        .astype("datetime64[ms]"),
        type=pa.timestamp("ms", tz="UTC"),
    )
    del ts
    nan_idx = rng.random(n) < 0.002
    flux_nan = flux.copy()
    flux_nan[nan_idx] = np.nan
    trail = rng.exponential(2.0, n)
    trail_arr = pa.array(trail, mask=rng.random(n) < 0.6)

    cols = {
        "diaSourceId": pa.array(np.arange(n, dtype=np.int64) + 170_000_000_000_000_000),
        "ssObjectId": pa.array(ss_obj, mask=ss_mask),
        "ra": ra,
        "dec": dec,
        "raErr": rng.uniform(1e-6, 3e-5, n).astype(np.float32),
        "decErr": rng.uniform(1e-6, 3e-5, n).astype(np.float32),
        "midpointMjdTai": mjd,
        "band": pa.array(BANDS[rng.integers(0, 6, n)]).dictionary_encode(),
        "psfFlux": flux_nan,
        "psfFluxErr": flux_err,
        "mag": mag.astype(np.float32),
        "snr": snr.astype(np.float32),
        "trailLength": trail_arr,
        "isDipole": rng.random(n) < 0.05,
        "detector": rng.integers(0, 189, n).astype(np.int16),
        "ingestTime": ingest,
    }
    units = {
        "diaSourceId": "[] Unique identifier of this DiaSource.",
        "ssObjectId": "[] Id of the solar system object this source was associated with, if any.",
        "ra": "[deg] Right ascension coordinate of the center of this diaSource.",
        "dec": "[deg] Declination coordinate of the center of this diaSource.",
        "raErr": "[deg] Uncertainty of ra.",
        "decErr": "[deg] Uncertainty of dec.",
        "midpointMjdTai": "[d] Effective mid-visit time for this diaSource, TAI MJD.",
        "band": "[] Filter band this source was observed with.",
        "psfFlux": "[nJy] Flux for Point Source model.",
        "psfFluxErr": "[nJy] Flux uncertainty for Point Source model.",
        "mag": "[mag] AB magnitude derived from psfFlux.",
        "snr": "[] Signal-to-noise ratio of the PSF flux.",
        "trailLength": "[arcsec] Length of the trail, when trailed.",
        "isDipole": "[] Source well fit by a dipole.",
        "detector": "[] Detector number.",
        "ingestTime": "[] Time this row was ingested.",
    }
    tbl = pa.table(cols)
    fields = [f.with_metadata({"description": units.get(f.name, "")}) for f in tbl.schema]
    schema = pa.schema(fields, metadata={
        "table": "DiaSource",
        "description": "Synthetic LSST-like DiaSource table generated by pqx.demo",
        "generator": "pqx.demo",
    })
    return tbl.cast(schema)


def write_demo(path: str, rows: int = 200_000, seed: int = 42, row_group_size: int = 65_536) -> str:
    tbl = make_table(rows, seed)
    pq.write_table(tbl, path, row_group_size=row_group_size, compression="zstd")
    return path


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description="Write a synthetic LSST-like Parquet file.")
    p.add_argument("path")
    p.add_argument("--rows", type=int, default=1_000_000)
    p.add_argument("--seed", type=int, default=42)
    a = p.parse_args(argv)
    write_demo(a.path, a.rows, a.seed, row_group_size=min(1_000_000, max(a.rows // 8, 1024)))
    print(f"wrote {a.rows:,} rows to {a.path}")


if __name__ == "__main__":
    main()
